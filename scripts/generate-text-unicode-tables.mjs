// Writes bindings/alpha2-text/src/unicode_tables.rs: the code point ranges of the Unicode
// properties alpha2-text reads that no crate in its graph exposes, from this Node's own Unicode
// data (process.versions.unicode). Run `node scripts/generate-text-unicode-tables.mjs` and commit
// the result.

import { writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const out = join(root, "bindings", "alpha2-text", "src", "unicode_tables.rs");

/** Inclusive ranges of the code points `pattern` matches. */
function ranges(pattern) {
  const found = [];
  let start = null;
  for (let code = 0; code <= 0x110000; code += 1) {
    const inside =
      code < 0x110000 &&
      !(code >= 0xd800 && code <= 0xdfff) &&
      pattern.test(String.fromCodePoint(code));
    if (inside && start === null) start = code;
    if (!inside && start !== null) {
      found.push([start, code - 1]);
      start = null;
    }
  }
  return found;
}

const hex = (code) => `0x${code.toString(16).padStart(4, "0")}`;
const table = (name, doc, pattern) =>
  [
    `/// ${doc}`,
    `pub(crate) const ${name}: &[(u32, u32)] = &[`,
    ...ranges(pattern).map(([from, to]) => `    (${hex(from)}, ${hex(to)}),`),
    "];",
  ].join("\n");

const text = [
  `// Generated by scripts/generate-text-unicode-tables.mjs from Unicode ${process.versions.unicode}; do not edit.`,
  "",
  table(
    "EXTENDED_PICTOGRAPHIC",
    "`Extended_Pictographic` (UTS #51): a pictograph, emoji or not; U+FE0F makes one an emoji.",
    /^\p{Extended_Pictographic}$/u,
  ),
  "",
  table(
    "EMOJI_PRESENTATION",
    "`Emoji_Presentation` (UTS #51): shown as an emoji unless U+FE0E asks for text.",
    /^\p{Emoji_Presentation}$/u,
  ),
  "",
  table(
    "DEFAULT_IGNORABLE",
    "`Default_Ignorable_Code_Point`: drawn as nothing, so no font needs a glyph for them.",
    /^\p{Default_Ignorable_Code_Point}$/u,
  ),
  "",
].join("\n");
await writeFile(out, text);
console.log(`wrote ${out}`);
