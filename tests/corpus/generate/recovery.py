#!/usr/bin/env python3
"""Corrupt fixture packet payloads while preserving timestamps and indexes.

Usage: recovery.py <corpus directory> <ffmpeg>

The ffmpeg needs libx264 and libvpx-vp9 (`generate.sh` passes FFMPEG_ENCODERS);
the ffprobe beside it reads the packets. The damaged ADTS stream is cut from
the corpus's `audio-adts.aac`, which `media.sh` writes first.
"""
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

root = Path(sys.argv[1]).resolve()
ffmpeg = sys.argv[2]
ffprobe = os.path.join(os.path.dirname(ffmpeg), 'ffprobe') if os.path.dirname(ffmpeg) else 'ffprobe'
manifest = []

def run(*args):
    subprocess.run(args, check=True)

def packets(path):
    return json.loads(subprocess.check_output([
        ffprobe, '-v', 'error', '-show_packets', '-of', 'json', str(path)
    ]))['packets']

for name, codec in [('h264', 'libx264'), ('vp9', 'libvpx-vp9'), ('mpeg4', 'mpeg4')]:
    base = root / f'recovery-{name}.mp4'
    run(ffmpeg, '-v', 'error', '-y', '-f', 'lavfi', '-i',
        'testsrc2=size=64x48:rate=10:duration=2', '-an', '-c:v', codec,
        '-g', '1', '-threads', '1', '-pix_fmt', 'yuv420p', str(base))
    data = bytearray(base.read_bytes())
    packet = packets(base)[10]
    pos, size = int(packet['pos']), int(packet['size'])
    data[pos:pos+size] = b'\xff' * size
    damaged = root / f'recovery-{name}-damaged.mp4'
    damaged.write_bytes(data)
    manifest.append(f'{damaged.name}: packet 10, PTS {packet["pts"]}, payload [{pos}, {pos+size}) replaced with FF')
base = root / 'recovery-aac.m4a'
run(ffmpeg, '-v', 'error', '-y', '-f', 'lavfi', '-i',
    'sine=frequency=997:sample_rate=48000:duration=2', '-c:a', 'aac', '-b:a', '96k', str(base))
data = bytearray(base.read_bytes())
packet = packets(base)[40]
pos, size = int(packet['pos']), int(packet['size'])
data[pos:pos+size] = bytes(size)
(root / 'recovery-aac-damaged.m4a').write_bytes(data)
manifest.append(f'recovery-aac-damaged.m4a: packet 40, PTS {packet["pts"]}, payload [{pos}, {pos+size}) replaced with 00')
base = root / 'audio-adts.aac'
data = base.read_bytes()
packet = packets(base)[-1]
end = int(packet['pos']) + int(packet['size']) // 2
(root / 'recovery-truncated.aac').write_bytes(data[:end])
manifest.append(f'recovery-truncated.aac: audio-adts.aac truncated to {end} bytes inside last ADTS packet')
for path in sorted(root.glob('recovery-*')):
    data = path.read_bytes()
    manifest.append(f'{path.name}: {len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()}')
(root / 'RECOVERY-MANIFEST.md').write_text('# Damaged input regression corpus\n\n'
    'Generated by `tests/corpus/generate/generate.sh recovery` using FFmpeg/ffprobe.\n'
    'Requires encoders libx264, libvpx-vp9, mpeg4 and aac; fixture hashes depend on encoder versions.\n'
    'Video: 64×48, 10 fps, 2 s, all intra; healthy prefix/suffix retain exact PTS.\n'
    'AAC: mono 48 kHz, 2 s; conceal exactly the missing packet at its source sample position.\n'
    'Strict rejects damage. Tolerant recovers the indexed inputs and ends the cut ADTS stream at its last whole frame.\n\n'
    + '\n'.join('- ' + line for line in manifest) + '\n')
